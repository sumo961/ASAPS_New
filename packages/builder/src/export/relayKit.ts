/**
 * relayKit — the "hide your API key" deployment story for exported HTML.
 *
 * An exported story with AI beats needs credentials at play time. Embedding
 * the author's key in the HTML means anyone can scrape it from a public
 * deployment. The relay kit is the alternative: a tiny serverless function
 * the author deploys NEXT TO the story (Netlify Drop understands the
 * netlify/functions/ folder convention out of the box). The player POSTs
 * { provider, body } to the same-origin function; the function injects the
 * key from the site's environment variables and forwards to the FIXED
 * official endpoint. The key never travels to the browser.
 *
 * Contract (mirrored by @asaps/core createRelayTransport):
 *   POST { provider: 'anthropic' | 'openai', body: <provider request body> }
 *   → provider-shaped JSON, status passed through.
 *
 * Reading aloud (mirrored by player-web WebTTSProvider), chosen by `target`:
 *   POST { provider: 'openai', target: 'realtime-secret', body: { session: { model } } }
 *   → OpenAI's short-lived Realtime secret; the player opens its own session
 *     with it, so the sound streams straight from OpenAI.
 *   POST { provider: 'openai', target: 'speech', body: <audio/speech body> }
 *   POST { provider: 'elevenlabs', target: 'speech', voiceId, latency?, body }
 *   → the sound, piped through.
 * A relay deployed before these existed answers them with an error, and the
 * player reads with the browser's voice.
 *
 * Voice input (mirrored by player-web WebSTTProvider):
 *   POST { provider: 'openai', target: 'transcribe', audio: <base64>, mime, model, language? }
 *   → OpenAI's transcription of the recording ({ text }). An earlier relay
 *     answers with an error and the player listens with the browser instead.
 *
 * Security posture (documented in the generated README):
 *   - Upstream URLs are HARDCODED — the client cannot redirect the relay.
 *   - No CORS headers are emitted, so browsers only allow same-origin
 *     calls: the key is only spendable from the site it's deployed on.
 *   - The key lives in Netlify env vars, never in the bundle.
 */

/** Default same-origin path where the Netlify function answers. */
export const DEFAULT_RELAY_PATH = '/.netlify/functions/asaps-ai';

/** Netlify Functions v2 (ESM, web Request/Response) relay source. */
export const RELAY_FUNCTION_SOURCE = `// ASAPS AI relay — generated by ASAPS Builder.
// Deploy next to your exported story (same-origin mode) OR as its own
// site shared by several stories (set ALLOWED_ORIGINS). Set
// ANTHROPIC_API_KEY and/or OPENAI_API_KEY in Project configuration →
// Environment variables (and ELEVENLABS_API_KEY for ElevenLabs voices).
// See README-RELAY.md for the walkthroughs.

const UPSTREAMS = {
  anthropic: 'https://api.anthropic.com/v1/messages',
  openai: 'https://api.openai.com/v1/chat/completions',
};

// Reading aloud. The player says which of these it wants with "target";
// the addresses are fixed here, as above.
const SPEECH_UPSTREAMS = {
  openai: {
    // A short-lived secret for one Realtime session. The player opens the
    // session itself, so the sound streams straight from OpenAI.
    'realtime-secret': 'https://api.openai.com/v1/realtime/client_secrets',
    speech: 'https://api.openai.com/v1/audio/speech',
    // Voice input: a recorded answer, to be written down.
    transcribe: 'https://api.openai.com/v1/audio/transcriptions',
  },
  elevenlabs: { speech: 'https://api.elevenlabs.io/v1/text-to-speech/' },
};
const KEY_NAMES = { anthropic: 'ANTHROPIC_API_KEY', openai: 'OPENAI_API_KEY', elevenlabs: 'ELEVENLABS_API_KEY' };

// A recorded answer (base64) goes to OpenAI as the file it expects.
const TRANSCRIBE_MODELS = /^(gpt-transcribe[a-z0-9.-]*|gpt-4o(-mini)?-transcribe|whisper-1)$/;
const AUDIO_TYPES = { 'audio/webm': 'webm', 'audio/mp4': 'mp4', 'audio/ogg': 'ogg', 'audio/wav': 'wav', 'audio/mpeg': 'mp3' };
const MAX_AUDIO_BASE64 = 5 * 1024 * 1024; // about a minute of speech is well under this

async function relayTranscription(payload, url, key, fail, cors) {
  const model = String(payload.model || 'gpt-transcribe');
  if (!TRANSCRIBE_MODELS.test(model)) return fail(400, 'Expected a transcription model');
  const mime = String(payload.mime || '').split(';')[0].trim().toLowerCase();
  const ext = AUDIO_TYPES[mime];
  const audio = payload.audio;
  if (!ext || typeof audio !== 'string' || audio.length === 0) return fail(400, 'Expected { audio: <base64>, mime: <audio type> }');
  if (audio.length > MAX_AUDIO_BASE64) return fail(413, 'The recording is too long');
  let bytes;
  try { bytes = Uint8Array.from(atob(audio), (c) => c.charCodeAt(0)); } catch { return fail(400, 'The recording could not be read'); }

  const form = new FormData();
  form.append('file', new Blob([bytes], { type: mime }), 'answer.' + ext);
  form.append('model', model);
  const language = String(payload.language || '');
  if (/^[a-z]{2,3}$/i.test(language)) {
    // gpt-transcribe takes a list and refuses the single field.
    form.append(/^gpt-transcribe/.test(model) ? 'languages[]' : 'language', language.toLowerCase());
  }
  const upstream = await fetch(url, { method: 'POST', headers: { authorization: 'Bearer ' + key }, body: form });
  return new Response(await upstream.text(), {
    status: upstream.status,
    headers: { 'content-type': upstream.headers.get('content-type') || 'application/json', 'cache-control': 'no-store', ...(cors || {}) },
  });
}

async function relaySpeech(payload, cors) {
  const { provider, target, body } = payload;
  const fail = (status, error) => Response.json({ error }, { status, headers: cors || {} });
  const base = SPEECH_UPSTREAMS[provider] && SPEECH_UPSTREAMS[provider][target];
  if (!base || (target !== 'transcribe' && (!body || typeof body !== 'object'))) {
    return fail(400, "Expected { provider: 'openai' | 'elevenlabs', target: 'speech' | 'realtime-secret', body: {...} }");
  }
  const key = process.env[KEY_NAMES[provider]];
  if (!key) {
    return fail(500, KEY_NAMES[provider] + ' is not set. Add it under Project configuration → Environment variables, then redeploy.');
  }

  if (target === 'transcribe') return relayTranscription(payload, base, key, fail, cors);

  let url = base;
  let send = body;
  const headers = { 'content-type': 'application/json' };
  if (provider === 'elevenlabs') {
    const voiceId = String(payload.voiceId || '');
    if (!/^[A-Za-z0-9_-]{1,64}$/.test(voiceId)) return fail(400, 'Expected a voiceId');
    url = base + voiceId + '/stream' + (payload.latency ? '?optimize_streaming_latency=' + (Number(payload.latency) | 0) : '');
    headers['xi-api-key'] = key;
  } else {
    headers.authorization = 'Bearer ' + key;
    if (target === 'realtime-secret') {
      // Only a reading session of a Realtime model, nothing else the caller asks for.
      const model = String((body.session && body.session.model) || '');
      if (!/^gpt-realtime[a-z0-9.-]*$/.test(model)) return fail(400, 'Expected a gpt-realtime model');
      send = { session: { type: 'realtime', model } };
    }
  }

  const upstream = await fetch(url, { method: 'POST', headers, body: JSON.stringify(send) });
  const type = upstream.headers.get('content-type') || 'application/json';
  // The sound is piped through as it arrives; a refusal keeps its status
  // and message, so the player can tell why and read with the browser's voice.
  if (upstream.ok && target === 'speech') {
    return new Response(upstream.body, { status: upstream.status, headers: { 'content-type': type, 'cache-control': 'no-store', ...(cors || {}) } });
  }
  return new Response(await upstream.text(), { status: upstream.status, headers: { 'content-type': type, 'cache-control': 'no-store', ...(cors || {}) } });
}

// Claude Opus 5 / 5.5, Fable and Mythos run safety classifiers that can
// decline a harmless story scene. For those models the relay asks Anthropic
// to re-run a declined request on the model it recommends, instead of the
// AI beat failing. (Mirrors claudeSupportsServerFallbacks in @asaps/core.)
const FALLBACK_MODELS = /^claude-(fable-|mythos-|opus-([5-9]|\\d{2,}))/;
const FALLBACK_BETA = 'server-side-fallback-2026-07-01';

// Cross-origin access is opt-in via ALLOWED_ORIGINS (comma-separated).
// Entries are exact origins ("https://my-story.netlify.app") or
// suffix wildcards ("*.netlify.app" — any https site on that suffix).
// Unset ⇒ no CORS headers are emitted, so browsers only allow calls
// from THIS site's own pages (the co-located default).
function corsHeadersFor(req) {
  const raw = process.env.ALLOWED_ORIGINS;
  const origin = req.headers.get('origin');
  if (!raw || !origin) return null;
  let host;
  try {
    const u = new URL(origin);
    if (u.protocol !== 'https:' && u.hostname !== 'localhost') return null;
    host = u.hostname;
  } catch { return null; }
  const allowed = raw.split(',').map((e) => e.trim()).filter(Boolean).some((entry) => {
    if (entry.startsWith('*.')) return host.endsWith(entry.slice(1)); // ".netlify.app"
    try { return new URL(entry).origin === origin; } catch { return entry === origin; }
  });
  if (!allowed) return null;
  return {
    'access-control-allow-origin': origin,
    'access-control-allow-methods': 'POST, OPTIONS',
    'access-control-allow-headers': 'content-type',
    vary: 'Origin',
  };
}

export default async (req) => {
  const cors = corsHeadersFor(req);

  // Preflight for allowed cross-origin callers.
  if (req.method === 'OPTIONS') {
    return new Response(null, { status: cors ? 204 : 403, headers: cors || {} });
  }

  if (req.method !== 'POST') {
    return Response.json({ error: 'POST only' }, { status: 405, headers: cors || {} });
  }

  let payload;
  try {
    payload = await req.json();
  } catch {
    return Response.json({ error: 'Invalid JSON body' }, { status: 400, headers: cors || {} });
  }

  if (payload && payload.target) return relaySpeech(payload, cors);

  const { provider, body } = payload || {};
  if (!UPSTREAMS[provider] || !body || typeof body !== 'object') {
    return Response.json(
      { error: "Expected { provider: 'anthropic' | 'openai', body: {...} }" },
      { status: 400, headers: cors || {} },
    );
  }

  const key = provider === 'anthropic'
    ? process.env.ANTHROPIC_API_KEY
    : process.env.OPENAI_API_KEY;
  if (!key) {
    const name = provider === 'anthropic' ? 'ANTHROPIC_API_KEY' : 'OPENAI_API_KEY';
    return Response.json(
      { error: name + ' is not set. Add it under Project configuration → Environment variables, then redeploy.' },
      { status: 500, headers: cors || {} },
    );
  }

  const headers = provider === 'anthropic'
    ? {
        'content-type': 'application/json',
        'x-api-key': key,
        'anthropic-version': '2023-06-01',
      }
    : {
        'content-type': 'application/json',
        authorization: 'Bearer ' + key,
      };
  if (provider === 'anthropic' && body.fallbacks === undefined && FALLBACK_MODELS.test(String(body.model || ''))) {
    body.fallbacks = 'default';
    headers['anthropic-beta'] = FALLBACK_BETA;
  }

  const upstream = await fetch(UPSTREAMS[provider], {
    method: 'POST',
    headers,
    body: JSON.stringify(body),
  });

  // Streaming requests (body.stream === true) are PIPED through untouched.
  // This is what makes long generations (AI dialog trees) survive on
  // serverless hosts: buffered functions are killed at the execution cap
  // (Netlify: 10 s), while a streamed response starts within milliseconds
  // and may keep streaming for as long as the model generates. The player
  // reassembles the SSE back into the plain response shape.
  const upstreamType = upstream.headers.get('content-type') || '';
  if (body.stream === true && upstream.ok && upstreamType.includes('text/event-stream')) {
    return new Response(upstream.body, {
      status: upstream.status,
      headers: {
        'content-type': 'text/event-stream',
        'cache-control': 'no-cache',
        ...(cors || {}),
      },
    });
  }

  // Non-streaming: pass the provider-shaped JSON (and status) through
  // untouched so response parsing is identical for direct and relayed calls.
  return new Response(await upstream.text(), {
    status: upstream.status,
    headers: { 'content-type': 'application/json', ...(cors || {}) },
  });
};
`;

