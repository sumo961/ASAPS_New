export const RELAY_NETLIFY_TOML = `[build]
  publish = "."

[functions]
  directory = "netlify/functions"
`;

/** The environment variables a relay can need, by what the story uses it for. */
export type RelayKeyName = 'ANTHROPIC_API_KEY' | 'OPENAI_API_KEY' | 'ELEVENLABS_API_KEY';

/** Which keys this export's relay needs: the AI's provider, and the voices'. */
export function relayKeysFor(options: { aiProxyUrl?: string; aiProvider?: string; ttsRelayUrl?: string; ttsProvider?: string; sttRelayUrl?: string }): RelayKeyName[] {
  const keys = new Set<RelayKeyName>();
  if (options.aiProxyUrl) keys.add(options.aiProvider === 'anthropic' ? 'ANTHROPIC_API_KEY' : 'OPENAI_API_KEY');
  if (options.ttsRelayUrl) keys.add(options.ttsProvider === 'elevenlabs' ? 'ELEVENLABS_API_KEY' : 'OPENAI_API_KEY');
  // Voice input through the relay is OpenAI's transcription.
  if (options.sttRelayUrl) keys.add('OPENAI_API_KEY');
  return [...keys];
}

const ALL_RELAY_KEYS: RelayKeyName[] = ['ANTHROPIC_API_KEY', 'OPENAI_API_KEY', 'ELEVENLABS_API_KEY'];

/**
 * Path B of the README as one script: log in, create the site, set the
 * keys, deploy. Keys are typed unseen, handed to Netlify through a file
 * outside this folder that is deleted at once (never on a command line,
 * where other programs on the computer could read them), and marked secret.
 */
export function buildRelayDeployScript(keys: RelayKeyName[] = ALL_RELAY_KEYS): string {
  const asked = keys.length > 0 ? keys : ALL_RELAY_KEYS;
  const optional = keys.length === 0 || keys.length === ALL_RELAY_KEYS.length;
  return `#!/usr/bin/env bash
# ASAPS relay: deploy this folder to Netlify (path B in README-RELAY.md).
# Generated by ASAPS Builder. Run it from a terminal:   bash deploy.sh
# Run it again any time: after a new export (copy the new index.html here),
# or to change a key. Needs Node.js (https://nodejs.org) and a Netlify account.
set -euo pipefail
cd "$(dirname "$0")"

KEYS="${asked.join(' ')}"
NETLIFY="npx --yes netlify-cli"

say() { printf '\n== %s\n' "$1"; }

command -v npx >/dev/null 2>&1 || { echo "Node.js is needed (it brings npx). Install it from https://nodejs.org and run this again."; exit 1; }
[ -f index.html ] || { echo "index.html is not in this folder. Run the script inside the unzipped export."; exit 1; }
[ -f netlify/functions/asaps-ai.mjs ] || { echo "netlify/functions/asaps-ai.mjs is missing. Unzip the whole export and run the script there."; exit 1; }

say "1/4  Netlify login"
# ("status" ends without an error also when logged out: ask it in JSON.)
if $NETLIFY status --json 2>/dev/null | grep -q '"loggedIn"[[:space:]]*:[[:space:]]*true'; then
  echo "Already logged in."
else
  echo "A browser window opens: log in and click Authorize."
  $NETLIFY login
fi

say "2/4  The site"
if [ -f .netlify/state.json ]; then
  echo "This folder already belongs to a Netlify site: deploying to it again."
else
  echo "Creating a new site. Pick your team, and a name or leave it empty for a random one."
  $NETLIFY sites:create
fi

say "3/4  API keys (kept on Netlify, never in the page)"
${optional
    ? 'echo "Enter the keys the story uses. Leave one empty to skip it."'
    : 'echo "This story needs: $KEYS"'}
echo "What you type is not shown. Leave a key empty to keep what Netlify already has."
ENVFILE="$(mktemp)"
chmod 600 "$ENVFILE"
trap 'rm -f "$ENVFILE"' EXIT
SET=""
for KEY in $KEYS; do
  printf '%s: ' "$KEY"
  IFS= read -rs VALUE || VALUE=""
  echo
  VALUE="$(printf '%s' "$VALUE" | tr -d '[:space:]')"
  if [ -n "$VALUE" ]; then
    printf '%s=%s\n' "$KEY" "$VALUE" >> "$ENVFILE"
    SET="$SET $KEY"
  fi
  VALUE=""
done
if [ -n "$SET" ]; then
  $NETLIFY env:import "$ENVFILE" >/dev/null
  rm -f "$ENVFILE"
  for KEY in $SET; do
    # Marked secret: Netlify will not show the value again.
    $NETLIFY env:set "$KEY" --secret --force >/dev/null 2>&1 || echo "($KEY is set, but could not be marked secret. You can do that under Project configuration, Environment variables.)"
    echo "Set $KEY."
  done
else
  echo "No key entered: keeping what the site has."
fi

say "4/4  Deploy"
# --open: the story opens in the browser when it is up.
$NETLIFY deploy --prod --open

cat <<'DONE'

Done. The story should have opened in your browser; its address is the "Deployed to production URL" above.
- The output should list the function asaps-ai. If it does not, the netlify folder was not next to index.html.
- AI beats or voices not working: check that the key for them was entered (run this script again to set it).
- A new version of the story: export again, copy the new index.html into this folder, run this script again.
DONE
`;
}

export interface RelayKitFile {
  path: string;
  content: string;
  /** Unix file mode, for a file to run (the zip keeps it where the unzipping program does). */
  mode?: number;
}

/** The files the export writes for a relay deployment. */
export function buildRelayKitFiles(keys?: RelayKeyName[]): RelayKitFile[] {
  return [
    { path: 'netlify/functions/asaps-ai.mjs', content: RELAY_FUNCTION_SOURCE },
    { path: 'netlify.toml', content: RELAY_NETLIFY_TOML },
    { path: 'README-RELAY.md', content: RELAY_README },
    { path: 'deploy.sh', content: buildRelayDeployScript(keys), mode: 0o755 },
  ];
}
